import GLib from 'gi://GLib';

/** MIME types tried, in order, when a clipboard owner offers text. */
export const TEXT_MIMES = [
    'text/plain;charset=utf-8',
    'UTF8_STRING',
    'text/plain',
    'STRING',
];

/**
 * Image formats accepted from the clipboard. SVG is deliberately excluded:
 * it can carry scripts, and the Shell only needs raster previews.
 */
export const IMAGE_MIMES = [
    'image/png',
    'image/jpeg',
    'image/jpg',
    'image/webp',
    'image/gif',
    'image/bmp',
    'image/tiff',
];

const SAFE_ID = /^[A-Za-z0-9_-]+$/;
const SAFE_FILE = /^[A-Za-z0-9._-]+$/;

export function isTextMime(mime) {
    return typeof mime === 'string' &&
        (mime.startsWith('text/') || mime === 'STRING' || mime === 'UTF8_STRING');
}

export function isImageMime(mime) {
    return typeof mime === 'string' &&
        mime.startsWith('image/') &&
        mime !== 'image/svg+xml';
}

export function isSensitiveHint(value) {
    return /(?:secret|password|concealed|transient|autogenerated)/i.test(value ?? '');
}

export function isSafeFileName(name) {
    return typeof name === 'string' &&
        name.length > 0 &&
        name.length <= 255 &&
        !name.includes('..') &&
        SAFE_FILE.test(name);
}

export function decodeBytes(bytes) {
    return new TextDecoder('utf-8', {fatal: false}).decode(bytes.get_data());
}

export function normalizeText(text) {
    return String(text ?? '').replace(/\r\n?/g, '\n');
}

export function previewText(text, maxLength = 180) {
    const collapsed = normalizeText(text)
        .replace(/\s*\n\s*/g, ' ⏎ ')
        .replace(/[ \t]+/g, ' ')
        .trim();
    if (collapsed.length <= maxLength)
        return collapsed;
    return `${collapsed.slice(0, Math.max(0, maxLength - 1))}…`;
}

export function hashText(text) {
    return GLib.compute_checksum_for_string(GLib.ChecksumType.SHA256, text, -1);
}

export function hashBytes(bytes) {
    const checksum = new GLib.Checksum({checksum_type: GLib.ChecksumType.SHA256});
    const data = bytes instanceof Uint8Array ? bytes : bytes.get_data();
    checksum.update(data);
    return checksum.get_string();
}

function asDate(value) {
    const date = value instanceof Date ? value : new Date(value);
    return Number.isNaN(date.getTime()) ? new Date() : date;
}

function safeId(value) {
    return typeof value === 'string' && SAFE_ID.test(value)
        ? value
        : GLib.uuid_string_random();
}

/**
 * One clipboard history entry. Text is stored inline; image entries reference
 * files in the extension's data directory via their base names.
 */
export class ClipboardItem {
    constructor({
        id = null,
        kind,
        text = null,
        mime = null,
        image = null,
        thumb = null,
        hash,
        createdAt = new Date(),
        size = 0,
        sourceApp = null,
    }) {
        this.id = safeId(id);
        this.kind = kind === 'image' ? 'image' : 'text';
        this.text = this.kind === 'text' ? normalizeText(text) : null;
        this.mime = mime ?? (this.kind === 'text' ? 'text/plain;charset=utf-8' : 'image/png');
        this.image = this.kind === 'image' && isSafeFileName(image) ? image : null;
        this.thumb = this.kind === 'image' && isSafeFileName(thumb) ? thumb : null;
        this.hash = typeof hash === 'string' ? hash : '';
        this.createdAt = asDate(createdAt);
        this.size = Number.isFinite(size) ? size : 0;
        this.sourceApp = typeof sourceApp === 'string' && sourceApp ? sourceApp : null;
    }

    get preview() {
        if (this.kind === 'image')
            return 'Image';
        return previewText(this.text ?? '');
    }

    get searchText() {
        if (this.kind === 'image')
            return 'image';
        return this.text ?? '';
    }

    toJSON() {
        return {
            id: this.id,
            kind: this.kind,
            text: this.text,
            mime: this.mime,
            image: this.image,
            thumb: this.thumb,
            hash: this.hash,
            createdAt: this.createdAt.toISOString(),
            size: this.size,
            sourceApp: this.sourceApp,
        };
    }

    static fromJSON(value) {
        if (!value || typeof value !== 'object')
            return null;

        const kind = value.kind === 'image' ? 'image' : value.kind === 'text' ? 'text' : null;
        if (!kind || typeof value.hash !== 'string' || value.hash.length === 0)
            return null;

        if (kind === 'text') {
            if (typeof value.text !== 'string' || value.text.length === 0)
                return null;
            return new ClipboardItem({...value, kind});
        }

        if (!isSafeFileName(value.image))
            return null;

        return new ClipboardItem({
            ...value,
            kind,
            thumb: isSafeFileName(value.thumb) ? value.thumb : null,
        });
    }
}
